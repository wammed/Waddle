export function generateMarkdownReport(record: TestExecutionRecord): string {
  const suiteStats = TEST_SUITES.map((suite) => {
    const cases = TEST_CASES.filter((c) => c.suiteId === suite.id);
    const passed = cases.filter((c) => record.results[c.id]?.status === 'pass').length;
    const failed = cases.filter((c) => record.results[c.id]?.status === 'fail').length;
    return {
      nameJa: suite.nameJa,
      total: cases.length,
      passed,
      failed,
      notes: failed > 0 ? `${failed} 件の不合格あり` : '全項目合格確認済',
    };
  });

  const totalCases = TEST_CASES.length;
  const totalPassed = Object.values(record.results).filter((r) => r.status === 'pass').length;
  const totalFailed = Object.values(record.results).filter((r) => r.status === 'fail').length;
  const totalSkipped = Object.values(record.results).filter((r) => r.status === 'skip').length;
  const totalUntested = totalCases - (totalPassed + totalFailed + totalSkipped);

  let md = `### テスト実行記録 (Test Execution Evidence)
- **実行日**: ${record.date || new Date().toISOString().split('T')[0]}
- **テスター**: ${record.tester || 'Waddle Quality Assurance Team'}
- **環境**: ${record.environment || 'Linux (WebKitGTK 4.1, Node.js, Rust)'}
- **総合判定**: **[${record.overallResult}]** (合格: ${totalPassed} / 不合格: ${totalFailed} / 保留・スキップ: ${totalSkipped} / 未検証: ${totalUntested})

| スイート | 項目数 | 合格数 | 不合格数 | 備考 |
| :--- | :--- | :--- | :--- | :--- |
`;

  for (const s of suiteStats) {
    md += `| ${s.nameJa} | ${s.total} | ${s.passed} | ${s.failed} | ${s.notes} |\n`;
  }

  md += `\n### 詳細エビデンス & 特記事項\n\n`;

  const detailedItems = TEST_CASES.filter((c) => {
    const r = record.results[c.id];
    return r && (r.status === 'fail' || r.status === 'pass' || (r.note && r.note.trim().length > 0));
  });

  if (detailedItems.length > 0) {
    md += `| ID | テスト対象 | 判定 | 種別 | エビデンス・特記事項 |\n`;
    md += `| :--- | :--- | :--- | :--- | :--- |\n`;
    for (const item of detailedItems) {
      const res = record.results[item.id];
      const statusIcon = res.status === 'pass' ? '🟢 PASS' : res.status === 'fail' ? '🔴 FAIL' : res.status === 'skip' ? '🟡 SKIP' : '⚪ PENDING';
      const safeNote = (res.note || '').replace(/\|/g, '\\|').replace(/\n/g, '<br/>') || '-';
      md += `| **${item.id}** | ${item.titleJa} | ${statusIcon} | ${item.type} | ${safeNote} |\n`;
    }
  } else {
    md += `_個別メモ・特記事項なし_\n`;
  }

  return md;
}
